// Turns scripts/affixes/source.txt into src/lib/affixes/data.ts. Run from the project root: node scripts/affixes/build.cjs
// Nothing is guessed: every row of the source must parse, or the script stops and says which line failed.
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'source.txt');
const OUT = path.join('src', 'lib', 'affixes', 'data.ts');

const ITEMS = { Amulets: 'amulet', Boots: 'boots', Bracelets: 'bracelet', Gauntlets: 'gauntlet', Rings: 'ring' };
const STATS = ['HP Regen', 'MP Regen', 'Move Speed', 'Defense', 'Absorb', 'Block', 'Crit', 'ATK', 'AR', 'HP', 'MP'];

const lines = fs.readFileSync(SRC, 'utf8').split(/\r?\n/);
const rows = [];
const errors = [];
let item = null, kind = null, tier = null, rowLines = 0;

lines.forEach((raw, i) => {
  const line = raw.trim();
  if (!line || line.startsWith('#')) return;
  const n = i + 1;
  let m;
  if ((m = line.match(/^📂\s*(\w+)$/))) { item = ITEMS[m[1]]; if (!item) errors.push(`${n}: item desconhecido "${m[1]}"`); kind = null; tier = null; return; }
  if (line === 'Prefixes') { kind = 'prefix'; tier = null; return; }
  if (line === 'Suffixes') { kind = 'suffix'; tier = null; return; }
  if ((m = line.match(/^Tier ([1-4]) \((\d+)–(\d+)\)$/))) { tier = +m[1]; return; }
  if (line.startsWith('(No ')) return; // "(No Gauntlet-specific suffixes in this bracket)"

  rowLines++;
  m = line.match(/^(.+?)\s+(\d)–(\d)\s+(\d+)\s+(.+)$/);
  if (!m) { errors.push(`${n}: linha não entendida: ${line}`); return; }
  if (!item || !kind || !tier) { errors.push(`${n}: linha fora de item/prefixo/tier: ${line}`); return; }
  const stats = [];
  for (const part of m[5].split(',').map((s) => s.trim())) {
    const sm = part.match(/^(.+?)\s*\+(\d+(?:\.\d+)?)(?:–(\d+(?:\.\d+)?))?$/);
    if (!sm || !STATS.includes(sm[1])) { errors.push(`${n}: atributo não entendido "${part}"`); continue; }
    const min = +sm[2], max = sm[3] === undefined ? min : +sm[3];
    if (min > max) errors.push(`${n}: mínimo maior que o máximo em "${part}"`);
    stats.push([sm[1], min, max]);
  }
  if (+m[2] > +m[3]) errors.push(`${n}: raridade ${m[2]}–${m[3]} invertida`);
  rows.push({ name: m[1], item, kind, tier, rarity: [+m[2], +m[3]], weight: +m[4], stats, line: n });
});

if (rowLines !== rows.length || errors.length) {
  console.error('ERROS:\n' + errors.join('\n'));
  process.exit(1);
}

// The ring list in the supplied text has one block under "Prefixes" for Tier 4 whose names are suffixes (Marksman, Sniper, Regrowth...),
// and the site owner's own example calls Marksman a Tier 4 ring suffix. So Tier 4 ring rows are suffixes; the rest of the ring list stays prefixes.
for (const r of rows) if (r.item === 'ring' && r.tier === 4) r.kind = 'suffix';

const lineFor = (r) => `  { name: ${JSON.stringify(r.name)}, item: '${r.item}', kind: '${r.kind}', tier: ${r.tier}, rarity: [${r.rarity}], weight: ${r.weight}, stats: ${JSON.stringify(r.stats)} },`;

const out = `// GENERATED by scripts/affixes/build.cjs from scripts/affixes/source.txt: do not edit by hand (edit the source and run the script again).
// Affix pools of the game (Season 11), as supplied by the site owner.

export type ItemType = 'amulet' | 'boots' | 'bracelet' | 'gauntlet' | 'ring';
export type AffixKind = 'prefix' | 'suffix';
export type StatKey = 'HP' | 'MP' | 'HP Regen' | 'MP Regen' | 'Defense' | 'AR' | 'ATK' | 'Block' | 'Crit' | 'Absorb' | 'Move Speed';

export interface Affix {
  name: string;
  item: ItemType;
  kind: AffixKind;
  /** 1 to 4: the level bracket the affix lives in (see TIERS). */
  tier: 1 | 2 | 3 | 4;
  /** The rarity numbers as written in the source (min to max). */
  rarity: [number, number];
  /** Roll weight: the bigger, the more common. */
  weight: number;
  /** [stat, min, max] */
  stats: [StatKey, number, number][];
}

export const AFFIXES: Affix[] = [
${rows.map(lineFor).join('\n')}
];
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);

const count = {};
for (const r of rows) { const k = `${r.item} ${r.kind}`; count[k] = (count[k] || 0) + 1; }
console.log('ok:', rows.length, 'afixos');
console.log(count);
