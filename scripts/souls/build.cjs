// Turns the owner's spreadsheet (scripts/souls/source.json, read from Tabela_Souls_PrisonZONE.xlsx) into
// src/lib/soulLocations.ts: where each soul drops (and the soul level the sheet gives).
// The attributes and values are NOT taken from the sheet: they come from src/data/souls.json (the Soul Tree's own data).
// Run from the project root: node scripts/souls/build.cjs
const fs = require('fs');
const path = require('path');

const rows = require('./source.json').slice(1);
const souls = require('../../src/data/souls.json');
const norm = (s) => s.toLowerCase().replace(/ soul$/, '').replace(/[^a-z0-9]/g, '');

// The sheet calls it "Elite Crios"; the tree has it as "Crios Soul" (icon EliteCriosSoul).
const ALIAS = { elitecrios: 'crios' };
// Spelling variants of the same map inside the sheet.
const MAP_FIX = { 'Florest of Spirits': 'Forest of Spirits', 'Land of the Dusk': 'Land of Dusk' };

const byName = new Map(souls.map((s) => [norm(s.name), s]));
const out = {};
const errors = [];

for (const r of rows) {
  const k = ALIAS[norm(r.B)] ?? norm(r.B);
  const s = byName.get(k);
  if (!s) { errors.push(`soul da planilha sem par na árvore: ${r.B}`); continue; }
  const entry = (out[s.id] ??= { level: +r.C, where: [] });
  if (entry.level !== +r.C) errors.push(`${r.B}: níveis diferentes na planilha (${entry.level} e ${r.C})`);
  if (entry.where.length) continue; // the sheet repeats the location on every attribute row
  for (const part of r.H.trim().split(/\s+and\s+/)) {
    const m = part.trim().match(/^(.*?)\s*(?:\((\d+)\))?$/);
    const map = MAP_FIX[m[1]] ?? m[1];
    entry.where.push(m[2] === undefined ? [map] : [map, +m[2]]);
  }
}
for (const s of souls) if (!out[s.id]) errors.push(`soul da árvore sem local na planilha: ${s.name}`);
if (errors.length) { console.error('ERROS:\n' + errors.join('\n')); process.exit(1); }

const lines = souls.map((s) => `  ${JSON.stringify(s.id)}: ${JSON.stringify(out[s.id])},`);
const text = `// GENERATED by scripts/souls/build.cjs from scripts/souls/source.json (the owner's Tabela_Souls_PrisonZONE.xlsx): do not edit by hand.
// Where each soul drops. A place is [map name] or [map name, number in parentheses as written in the sheet].
// \`level\` is the soul level given by the sheet (the tree has no level for some souls).

export interface SoulWhere { level: number; where: ([string] | [string, number])[] }

export const SOUL_WHERE: Record<string, SoulWhere> = {
${lines.join('\n')}
};
`;
fs.writeFileSync(path.join('src', 'lib', 'soulLocations.ts'), text);
console.log('ok:', souls.length, 'souls');
